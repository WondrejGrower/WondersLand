export function drawSkillIcon(ctx,id,x=0,y=0){
 const icon=symbols[id];
 if(!icon)return;
 const colors={1:icon.colors[0],2:icon.colors[1],3:icon.colors[2],'#':outline};
 for(const [row,line] of icon.rows.entries()){
  for(let col=0;col<line.length;col++){
   const color=colors[line[col]];
   if(color){ctx.fillStyle=color;ctx.fillRect(x+col,y+row,1,1);}
  }
 }
}
