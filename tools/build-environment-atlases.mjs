// Inspect the real alpha bounds of each approved motif; retain PNGs unchanged.
// Node >=22 + ImageMagick 7. Normal builds use the committed region metadata.
import {execFileSync} from 'node:child_process';import {readFileSync,writeFileSync} from 'node:fs';
const sources=JSON.parse(readFileSync('assets/art-source/2026-11-08/manifest.json')).environmentAtlases;
const regions={};
for(let i=0;i<2;i++){
 const key=i?'flora':'camp',w=1536,h=1024,bytes=execFileSync('magick',['assets/runtime/'+key+'.png','-depth','8','rgba:-'],{maxBuffer:16*1024*1024});
 const ys=i?[0,280,580,1024]:[0,350,705,1024];
 for(const item of sources[i].components){
  const row=item.row-1,col=item.column-1,xs=i?(row===2?[0,330,680,1180,1536]:[0,384,768,1152,1536]):row===2?[0,440,800,1170,1536]:[0,440,840,1170,1536];
  let left=xs[col+1],right=xs[col],top=ys[row+1],bottom=ys[row];
  for(let y=ys[row];y<ys[row+1];y++)for(let x=xs[col];x<xs[col+1];x++)if(bytes[(y*w+x)*4+3]>=100){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  if(right<=left||bottom<=top)throw Error('Missing alpha region: '+item.id);
  regions[item.id]={atlas:key,rect:[left,top,right-left+1,bottom-top+1]};
 }
}
writeFileSync('assets/runtime/environment-regions.json',JSON.stringify(regions,null,2)+'\n');
writeFileSync('web/environment-regions.mjs','// Generated by tools/build-environment-atlases.mjs.\nvar regions='+JSON.stringify(regions)+';\nexport {regions};\n');
console.log('Inspected',Object.keys(regions).length,'transparent environment regions');
