// Convert approved PNG source regions to a shared nearest-neighbour pixel library.
// Requires Node >=22 and ImageMagick 7 (magick). No generative step at build time.
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
const manifest=JSON.parse(readFileSync('assets/art-source/2026-11-08/manifest.json'));
function image(path,w,h){const bytes=execFileSync('magick',[path,'-depth','8','rgba:-'],{maxBuffer:24*1024*1024});if(bytes.length!==w*h*4)throw Error('Unexpected image dimensions: '+path);return {bytes,w,h};}
const art=image('assets/runtime/customization.png',1374,1145),body=image('assets/runtime/body-animation.png',1536,1024);
function bounds(im,rect){let [x0,y0,x1,y1]=rect,left=x1,top=y1,right=x0,bottom=y0;for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++){const p=(y*im.w+x)*4;if(im.bytes[p+3]>=160){left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);}}return [left,top,right-left+1,bottom-top+1];}
const palette=[null],indices=new Map();
function pixel(im,x,y){if(x<0||y<0||x>=im.w||y>=im.h)return 0;const p=(y*im.w+x)*4,b=im.bytes;if(b[p+3]<160)return 0;const color='#'+[b[p],b[p+1],b[p+2]].map(n=>Math.min(255,Math.round(n/8)*8).toString(16).padStart(2,'0').slice(-2)).join('');if(!indices.has(color)){indices.set(color,palette.length);palette.push(color);}return indices.get(color);}
function sample(im,rect,w,h){return {w,h,pixels:Array.from({length:w*h},(_,n)=>pixel(im,Math.floor(rect[0]+(n%w+.5)*rect[2]/w),Math.floor(rect[1]+(Math.floor(n/w)+.5)*rect[3]/h)))};}
const sprites={},regions={},xb=[40,260,474,688,903,1117,1340],yb=[40,247,449,680,904,1120];
for(const [i,item]of manifest.components.entries()){
 const c=item.column-1,r=item.row-1,rect=bounds(art,[xb[c],yb[r],xb[c+1],yb[r+1]]);regions[item.id]=rect;
 const size=i<16?[18,i>=12?20:15]:item.slot==='head'?[22,18]:item.slot==='torso'?[18,17]:item.slot==='legs'?[12,13]:item.slot==='belt'?[15,7]:[14,7];
 sprites[item.id]=sample(art,rect,...size);
}
// Common 24x40 registration. Crop bounds were inspected against all 12 poses.
// Each pose keeps its real limb silhouette rather than moving a single cutout.
const bodyBounds=[];
for(let i=0;i<12;i++){
 const col=i%6,row=Math.floor(i/6),rect=bounds(body,[col*256,row*512,(col+1)*256,(row+1)*512]);bodyBounds.push(rect);
 const h=40,scale=40/300,headOffset=i===10?9:i===8?0:1,anchorX=i===11?9:12;
 const headCenters=[148,400,650,905,1158,1410,145,400,642,897,1143,1372];
 const top=i===10?rect[1]-headOffset/scale:rect[1]-headOffset/scale;
 const left=headCenters[i]-anchorX/scale;
 sprites['body_'+i]=sample(body,[left,top,24/scale,h/scale],24,h);
}
writeFileSync('assets/runtime/regions.json',JSON.stringify({art:regions,body:bodyBounds},null,2)+'\n');
writeFileSync('src/CharacterSprites.js','.pragma library\n// Generated by tools/build-character-sprites.mjs; source PNGs remain unchanged.\nvar palette='+JSON.stringify(palette)+';\nvar sprites='+JSON.stringify(sprites)+';\n');
console.log('Compiled',Object.keys(sprites).length,'sprite regions;',palette.length,'shared palette entries');
