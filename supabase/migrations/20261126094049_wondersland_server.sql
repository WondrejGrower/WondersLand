-- Supabase owns all server progress and monthly history. No browser Data API access.
CREATE SCHEMA wonderland_private;
REVOKE ALL ON SCHEMA wonderland_private FROM PUBLIC, anon, authenticated;
DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='wonderland_server') THEN CREATE ROLE wonderland_server NOLOGIN; END IF; END $$;
GRANT wonderland_server TO postgres;
SET search_path TO wonderland_private, pg_catalog;
CREATE TABLE score_months (month TEXT PRIMARY KEY);
CREATE TABLE scores (month TEXT NOT NULL, owner TEXT NOT NULL, name TEXT NOT NULL, best bigint NOT NULL, total bigint NOT NULL, runs bigint NOT NULL, best_at bigint NOT NULL, updated bigint NOT NULL, rules TEXT NOT NULL, PRIMARY KEY(month,owner));
CREATE TABLE security_migrations (id TEXT PRIMARY KEY);
CREATE TABLE tickets (id TEXT PRIMARY KEY, owner TEXT NOT NULL, run_id TEXT NOT NULL, name TEXT NOT NULL, role TEXT NOT NULL, rules TEXT NOT NULL, started bigint NOT NULL, expires bigint NOT NULL, used bigint NOT NULL DEFAULT 0, score bigint, month TEXT, UNIQUE(owner,run_id));
CREATE TABLE verified_months (month TEXT NOT NULL,rules TEXT NOT NULL,PRIMARY KEY(month,rules));
CREATE TABLE verified_players (owner TEXT PRIMARY KEY, public_id TEXT UNIQUE NOT NULL, profile TEXT NOT NULL, updated bigint NOT NULL);
CREATE TABLE verified_registrations (source TEXT NOT NULL,day bigint NOT NULL,hits bigint NOT NULL,PRIMARY KEY(source,day));
CREATE TABLE verified_runs (id TEXT PRIMARY KEY, owner TEXT UNIQUE NOT NULL, snapshot TEXT NOT NULL, sequence bigint NOT NULL, frames bigint NOT NULL, started bigint NOT NULL, last_feed bigint NOT NULL, expires bigint NOT NULL, used bigint NOT NULL DEFAULT 0, last_hash TEXT, last_reply TEXT);
CREATE TABLE verified_scores (month TEXT NOT NULL, rules TEXT NOT NULL, owner TEXT NOT NULL, public_id TEXT NOT NULL, name TEXT NOT NULL, best bigint NOT NULL,total bigint NOT NULL,runs bigint NOT NULL,best_at bigint NOT NULL,updated bigint NOT NULL,PRIMARY KEY(month,rules,owner));
CREATE INDEX monthly_attempts ON scores(month,runs DESC,updated ASC,owner ASC);
CREATE INDEX monthly_best_v2 ON scores(month,best DESC,best_at ASC,owner ASC);
CREATE INDEX monthly_total ON scores(month,total DESC,updated ASC,owner ASC);
CREATE INDEX tickets_expiry ON tickets(expires);
CREATE INDEX verified_attempts ON verified_scores(month,rules,runs DESC,updated ASC,public_id ASC);
CREATE INDEX verified_best ON verified_scores(month,rules,best DESC,best_at ASC,public_id ASC);
CREATE INDEX verified_expiry ON verified_runs(used,expires);
CREATE INDEX verified_registration_expiry ON verified_registrations(day);
CREATE INDEX verified_total ON verified_scores(month,rules,total DESC,updated ASC,public_id ASC);
CREATE TABLE rate_limits (key text PRIMARY KEY CHECK(length(key)<=128),bucket bigint NOT NULL,hits integer NOT NULL);
CREATE INDEX rate_limits_bucket ON rate_limits(bucket);
CREATE TABLE migration_state (id integer PRIMARY KEY CHECK(id=1),complete boolean NOT NULL DEFAULT false,table_index integer NOT NULL DEFAULT 0,row_offset integer NOT NULL DEFAULT 0,counts jsonb NOT NULL DEFAULT '{}'::jsonb,bridge_key text CHECK(bridge_key ~ '^[a-f0-9]{64}$'));
